function withHoshana(lines) {
  var out = []
  for (var i = 0; i < opening.length; i++) out.push(rev(opening[i]))
  out.push("")
  for (var j = 0; j < lines.length; j++) out.push(rev("הוֹשַׁעְנָא " + lines[j]))
  out.push("")
  out.push(rev("אֲנִי וָהוּ הוֹשִׁיעָה נָּא"))
  return out
}

function section(title, lines) {
  var out = [rev(title), ""]
  var body = withHoshana(lines)
  for (var i = 0; i < body.length; i++) out.push(body[i])
  out.push("")
  return out
}

