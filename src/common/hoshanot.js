function isMark(ch) {
  var c = ch.charCodeAt(0)
  return (c >= 0x0591 && c <= 0x05C7)
}

function rev(text) {
  var chars = text.split("")
  var clusters = []
  for (var i = 0; i < chars.length; i++) {
    if (isMark(chars[i]) && clusters.length > 0) {
      clusters[clusters.length - 1] += chars[i]
    } else {
      clusters.push(chars[i])
    }
  }
  return clusters.reverse().join("")
}

